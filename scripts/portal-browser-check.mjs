import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync } from 'node:fs';
import { createApp } from '../server/index.js';
import { createStore } from '../server/store.js';

const store = createStore(':memory:');
const {server} = createApp({store,config:{provider:'ollama',baseUrl:'http://127.0.0.1:1',chatModel:'',embeddingModel:''}});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base=`http://127.0.0.1:${server.address().port}`;
const executablePath=process.env.BROWSER_PATH;
if(executablePath && !existsSync(executablePath))throw new Error('BROWSER_PATH tidak ditemukan.');
mkdirSync('.artifacts',{recursive:true});
let browser;
try {
  browser=await chromium.launch({headless:true,...(executablePath?{executablePath}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'}), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  await page.goto(base);
  await page.locator('#catalog-count').filter({hasText:'3 sumber'}).waitFor();
  assert.equal(await page.title(),'Simulasi Portal Satu Data Kota Depok');
  assert.equal(await page.locator('.portal-logo img').evaluate(img=>img.complete && img.naturalWidth>0),true);
  assert.equal(await page.locator('.hero-art img').evaluate(img=>img.complete && img.naturalWidth>0),true);
  await page.screenshot({path:'.artifacts/portal-depok-desktop.png',fullPage:true});
  await page.locator('#portal-query').fill('penduduk');
  await page.locator('#portal-search button').click();
  assert.equal(await page.locator('.dataset-card').count(),1);
  assert.match(await page.locator('.dataset-card').innerText(),/Kelurahan Depok/);
  await page.locator('#reset-search').click();
  assert.equal(await page.locator('.dataset-card').count(),3);
  await page.locator('[data-tab="metadata"]').click();
  assert.equal(await page.locator('.dataset-card').count(),1);
  await page.locator('[data-tab="all"]').click();
  await page.locator('#portal-query').fill('tidak-ada-dalam-koleksi');
  await page.locator('#portal-search button').click();
  await page.getByText('Belum ada sumber yang cocok dalam koleksi prototipe.',{exact:false}).waitFor();
  await page.locator('#reset-search').click();
  console.log('PASS Portal, aset asli lokal, pencarian/filter katalog, dan keadaan hasil kosong');

  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
  await page.locator('#chat-launcher').click();
  await page.getByRole('dialog',{name:'Popup Asisten Data Depok'}).waitFor();
  assert.equal(await page.locator('#chat-launcher').getAttribute('aria-expanded'),'true');
  assert.equal(await page.locator('.widget-start').getAttribute('href'),'/chat');
  await page.screenshot({path:'.artifacts/portal-depok-popup.png',fullPage:false});
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#chat-widget').isHidden(),true);
  assert.equal(await page.locator('#chat-launcher').evaluate(el=>el===document.activeElement),true);
  await page.locator('#chat-launcher').click();
  await page.locator('[data-widget-question*="metadata"]').click();
  await page.locator('.mini-excerpt').first().waitFor();
  assert.match(await page.locator('#widget-thread').innerText(),/LATIHAN/);
  await page.locator('.widget-footer a').click();
  await page.waitForURL('**/chat');
  await page.locator('.excerpts li').first().waitFor();
  assert.match(await page.locator('#messages').innerText(),/metadata/i);
  const theme=await page.locator('.new-chat').evaluate(el=>getComputedStyle(el).backgroundColor);
  assert.equal(theme,'rgb(36, 48, 98)');
  await page.locator('.portal-back').click();
  await page.waitForURL(base+'/');
  await page.locator('#chat-launcher').click();
  await page.locator('.mini-excerpt').first().waitFor();
  console.log('PASS Popup buka/tutup/Escape/fokus, tanya cepat → chatbot penuh, tema navy, dan riwayat dua arah');

  await page.goto(base+'/chat?question=Apa%20arti%20metadata%3F');
  await page.waitForURL(base+'/chat');
  await page.getByText('Apa arti metadata?',{exact:true}).waitFor();
  await page.locator('.excerpts li').first().waitFor();
  await page.goto(base+'/chat?source=kandidat-sampah');
  await page.locator('#source-dialog[open]').waitFor();
  assert.match(await page.locator('#dialog-title').innerText(),/sampah/i);
  console.log('PASS Tautan pertanyaan dan kartu sumber membuka tujuan yang benar');

  await page.locator('#close-source-dialog').click();
  assert.equal(await page.locator('#import-button').count(),0);
  await page.locator('#new-chat').click();
  await page.locator('#welcome').waitFor();
  assert.ok(await page.locator('.conversation-item').count()>0);
  await page.screenshot({path:'.artifacts/full-chat-depok-desktop.png',fullPage:true});
  await page.locator('.prompt-card[data-prompt*="metadata"]').click();
  await page.locator('.excerpts li').first().waitFor();
  await page.screenshot({path:'.artifacts/full-chat-depok-answer.png',fullPage:true});
  await page.locator('.answer-actions [data-export]').first().click();
  await page.locator('#new-chat').click();
  const archived=page.locator('.conversation-item').first();
  await archived.click();
  await page.locator('.excerpts li').first().waitFor();
  await page.reload();
  await page.locator('.excerpts li').first().waitFor();
  await page.locator('#history-search').fill('tidak-ada-percakapan-ini');
  await page.getByText('Belum ada percakapan yang cocok.',{exact:true}).waitFor();
  await page.locator('#history-search').fill('');
  console.log('PASS Full chat: tampilan pengunjung, percakapan baru/arsip, unduh, pencarian riwayat, dan reload');

  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,reducedMotion:'reduce'});
  mobile.on('pageerror',error=>errors.push(error.message));
  await mobile.goto(base);
  await mobile.locator('#catalog-count').filter({hasText:'3 sumber'}).waitFor({state:'attached'});
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await mobile.screenshot({path:'.artifacts/portal-depok-mobile.png',fullPage:true});
  await mobile.locator('#mobile-menu').click();
  await mobile.locator('#portal-navigation a[href="#tentang"]').waitFor({state:'visible'});
  await mobile.locator('#portal-navigation a[href="#tentang"]').click();
  assert.equal(await mobile.locator('#mobile-menu').getAttribute('aria-expanded'),'false');
  await mobile.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
  await mobile.locator('#chat-launcher').click();
  await mobile.screenshot({path:'.artifacts/portal-depok-popup-mobile.png',fullPage:false});
  const rect=await mobile.locator('#chat-widget').boundingBox();
  assert.ok(rect.x>=0 && rect.y>=0 && rect.x+rect.width<=390 && rect.y+rect.height<=844);
  await mobile.locator('.widget-start').click();
  await mobile.waitForURL('**/chat');
  await mobile.locator('#welcome').waitFor();
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await mobile.screenshot({path:'.artifacts/full-chat-depok-mobile.png',fullPage:true});
  await mobile.locator('#open-sidebar').click();
  await mobile.locator('#close-sidebar').waitFor({state:'visible'});
  await mobile.keyboard.press('Escape');
  assert.equal(await mobile.locator('#open-sidebar').getAttribute('aria-expanded'),'false');
  await mobile.locator('#toggle-sources').click();
  await mobile.locator('#reference-panel').waitFor({state:'visible'});
  await mobile.keyboard.press('Escape');
  await mobile.locator('.prompt-card[data-prompt*="metadata"]').click();
  await mobile.locator('.excerpts li').first().waitFor();
  await mobile.locator('.answer-actions [data-references]').first().click();
  await mobile.locator('.reference-source').first().waitFor({state:'visible'});
  await mobile.locator('.reference-source').first().click();
  await mobile.locator('#source-dialog[open]').waitFor();
  await mobile.locator('#close-source-dialog').click();
  await mobile.keyboard.press('Escape');
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  console.log('PASS Mobile: navigasi portal, popup muat di layar, tombol masuk chatbot, tanpa overflow');
  console.log('PASS Full chat mobile: drawer riwayat/sumber, Escape, jawaban, dan detail rujukan');
  assert.deepEqual(errors,[]);
  console.log('PASS Tidak ada pageerror/console error pada alur portal dan chatbot');
} finally {
  if(browser)await browser.close();
  await new Promise(resolve=>server.close(resolve));store.close();
}
